import { z } from "zod";
import { createHash, randomUUID } from "node:crypto";

export const fields = ["summary", "strengths", "weaknesses", "questions", "limitations", "ethics", "justification"];
export const emptyForm = () => ({ ...Object.fromEntries([...fields.map(k => [k, ""]), ...["soundness", "presentation", "contribution", "rating", "confidence"].map(k => [k, ""])]), organization: "" });
const text = z.string().max(60000);
export const formSchema = z.object({
  organization: text.optional(),
  ...Object.fromEntries(fields.map(k => [k, text])),
  soundness: z.string().max(100), presentation: z.string().max(100), contribution: z.string().max(100),
  rating: z.string().max(100), confidence: z.string().max(100),
}).strict();
export const normalizeQuote = value => value.normalize("NFKC").replace(/(\w)-\s+(\w)/g, "$1$2").replace(/\s+/g, "").toLowerCase();
export function locateQuote(pages, pageNumber, quote) {
  const page = pages.find(p => p.number === pageNumber);
  const needle = normalizeQuote(quote);
  return Boolean(page && needle.length >= 12 && normalizeQuote(page.text).includes(needle));
}
export function validateFindings(findings, pages, runId) {
  return findings.map(f => ({ ...f, id: randomUUID(), runId, source: "ai", status: "open", time: new Date().toISOString(),
    anchored: locateQuote(pages, f.page, f.quote),
    certainty: locateQuote(pages, f.page, f.quote) ? f.certainty : "unverified",
  }));
}
export async function extractPDF(buffer) {
  if (!buffer.subarray(0, 1024).includes(Buffer.from("%PDF-"))) throw new Error("请上传有效的 PDF 文件");
  const { getDocument } = await import("pdfjs-dist/legacy/build/pdf.mjs");
  const task = getDocument({ data: new Uint8Array(buffer), isEvalSupported: false, useSystemFonts: true });
  try {
    const doc = await task.promise;
    if (doc.numPages > 150) throw new Error("最多支持 150 页 PDF，请拆分附件后导入");
    const pages = [];
    for (let number = 1; number <= doc.numPages; number++) {
      const page = await doc.getPage(number);
      const content = await page.getTextContent();
      const viewport = page.getViewport({ scale: 1 });
      const items = content.items.filter(i => typeof i.str === "string").map(i => ({
        text: i.str, x: i.transform[4], y: i.transform[5], width: i.width, height: i.height, eol: i.hasEOL,
      }));
      pages.push({ number, width: viewport.width, height: viewport.height, text: items.map(i => i.text + (i.eol ? "\n" : " ")).join(""), items });
      page.cleanup();
    }
    const metadata = await doc.getMetadata().catch(() => null);
    return { pages, title: String(metadata?.info?.Title || "").trim(), hash: createHash("sha256").update(buffer).digest("hex") };
  } finally { await task.destroy(); }
}
export function reviewMarkdown(paper) {
  const labels = { summary: "Summary", strengths: "Strengths", weaknesses: "Weaknesses", questions: "Questions", limitations: "Limitations", ethics: "Ethical Concerns", justification: "Rating Justification" };
  return [`# ${paper.title}`, `Venue: ${paper.venue}`, "Status: Human-edited draft; not submitted to OpenReview.",
    "Rating legend: verify against your assigned OpenReview form; numeric scales are not automatically certified for this year.",
    ...fields.map(k => `## ${labels[k]}\n\n${paper.form[k] || "[Not completed]"}`),
    ...["soundness", "presentation", "contribution", "rating", "confidence"].map(k => `## ${k[0].toUpperCase() + k.slice(1)}\n\n${paper.form[k] || "[Not assigned by reviewer]"}`),
    `## AI 整理（可编辑草稿，未经提交）\n\n${paper.form.organization || "[Not completed]"}`,
    "## AI Assistance Disclosure", `AI review runs: ${paper.runs.length}. Cloud passage translations: ${paper.translations?.length || 0}. AI reading/explanation interactions: ${paper.readings?.filter(r => r.mode !== "organize").length || 0}. AI organization interactions: ${paper.readings?.filter(r => r.mode === "organize").length || 0}. AI suggestions, translations and explanations require human verification.`,
    `Original human assessment (recorded separately, never generated by AI):\n\n${paper.initialAssessment?.text || "[Not recorded; do not represent AI-first exploration as an unaided assessment.]"}`,
    `Full prompts, outputs, evidence and revision history are included in the JSON export.`,
    ...paper.findings.filter(f => f.status === "accepted").map(f => `### ${f.title}\n\np. ${f.page}: ${f.quote}\n\n${f.body}\n\n${f.request || ""}`),
  ].join("\n\n");
}
